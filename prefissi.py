def get_prefissi_internazionali() -> list[str]:
    """Restituisce la lista completa di tutti i prefissi internazionali formattati

    in ordine numerico crescente (es. '+1 🇨🇦 Canada', ..., '+39 🇮🇹 Italia', ..., '+998 🇺🇿 Uzbekistan').
    """
    ordinati = sorted(
        PAESI_PREFISSI,
        key=lambda x: (int(x[0].replace("+", "")), x[2]),
    )
    return [f"{codice} {bandiera} {paese}" for codice, bandiera, paese in ordinati]


def separa_prefisso_e_numero(numero_completo: Any) -> tuple[str, str]:
    """Separa il prefisso internazionale dal numero locale di telefono."""
    valore = str(numero_completo or "").strip()
    if not valore or valore.lower() == "nan":
        return "+39", ""

    prefissi_unici = {p[0] for p in PAESI_PREFISSI}
    prefissi_ordinati_lunghezza = sorted(prefissi_unici, key=len, reverse=True)

    if valore.startswith("+"):
        for p in prefissi_ordinati_lunghezza:
            if valore.startswith(p):
                return p, valore[len(p) :].strip()
        return "+39", valore.lstrip("+")

    if valore.startswith("39") and len(valore) > 9:
        return "+39", valore[2:].strip()

    return "+39", valore
